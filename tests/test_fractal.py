"""Tests for src/features/fractal.py.

Two kinds of coverage:
1. Analytical sanity checks (white noise -> H near 0.5, degenerate signals -> NaN).
2. Golden-fixture regression: tests/fixtures/fractal_golden.npz was generated by
   scripts/_gen_fractal_golden.py using the pre-refactor implementation. Any
   performance refactor (vectorizing the R/S-family block loops, removing the
   duplicate compute_ho call, etc.) MUST keep compute_all_fractals() numerically
   identical (within float tolerance) to this fixture. If a change is intended
   to alter numeric output (e.g. the HRS_p64 correctness fix), regenerate the
   fixture deliberately and note why in the commit message.
"""
import os

import numpy as np
import pytest

import config as cfg
from src.features.fractal import (
    compute_all_fractals,
    compute_dfa,
    compute_higuchi,
    compute_ho,
    compute_hrs,
    compute_hrs_vector,
    compute_rs,
    compute_variogram,
)

FIXTURES_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "fixtures")


# ---------------------------------------------------------------------------
# Analytical sanity checks
# ---------------------------------------------------------------------------

def _white_noise(n=4000, seed=0):
    rng = np.random.default_rng(seed)
    return rng.standard_normal(n)


def test_rs_white_noise_near_half():
    h = compute_rs(_white_noise(4000), fs=cfg.FS)
    assert not np.isnan(h)
    assert 0.3 < h < 0.7, f"expected H near 0.5 for white noise, got {h}"


def test_dfa_white_noise_near_half():
    alpha = compute_dfa(_white_noise(4000), fs=cfg.FS)
    assert not np.isnan(alpha)
    assert 0.3 < alpha < 0.7, f"expected alpha near 0.5 for white noise, got {alpha}"


def test_constant_signal_returns_nan():
    sig = np.ones(700) * 3.0
    assert np.isnan(compute_rs(sig, fs=cfg.FS))
    assert np.isnan(compute_dfa(sig, fs=cfg.FS))
    assert np.isnan(compute_variogram(sig, fs=cfg.FS))
    assert np.isnan(compute_ho(sig, fs=cfg.FS))


def test_too_short_signal_returns_nan():
    sig = _white_noise(10)
    assert np.isnan(compute_rs(sig, fs=cfg.FS))
    assert np.isnan(compute_ho(sig, fs=cfg.FS))


def test_higuchi_reasonable_range():
    d = compute_higuchi(_white_noise(700), fs=cfg.FS)
    assert not np.isnan(d)
    # Fractal dimension for a 1D curve is bounded in [1, 2]; white noise
    # should be close to the upper end (highly irregular).
    assert 1.0 <= d <= 2.5


def test_compute_all_fractals_shape():
    seg = _white_noise(700 * 16).reshape(16, 700)
    feats = compute_all_fractals(seg, fs=cfg.FS)
    assert feats.shape == (16, 8)


def test_hv_column_equals_variogram_column():
    """Documented design choice (not a bug): HV is a literal alias of Variogram."""
    seg = np.cumsum(np.random.default_rng(1).standard_normal((16, 700)), axis=1)
    feats = compute_all_fractals(seg, fs=cfg.FS)
    np.testing.assert_array_equal(feats[:, 3], feats[:, 7])  # Variogram == HV


# ---------------------------------------------------------------------------
# HRS_p64 correctness regression (Fase 2 fix)
#
# Bug history: for every window length used in this study (500-2000 samples,
# i.e. 2.0-8.0s @ 250Hz), compute_hrs(x, p=64) silently fell back to
# compute_ho(x) — the "partitioned" HRS feature was never actually computed
# with partitions. config.BEST_HRS_PARTITION was changed from 64 to 8, the
# largest value empirically confirmed to still exercise real per-subseries
# R/S pooling at N=700. These tests pin that behavior down so a future
# change to config.BEST_HRS_PARTITION, or to the fallback thresholds in
# compute_hrs, can't silently regress back into the bug.
# ---------------------------------------------------------------------------

W700_N = 700


def _fbm(n, seed):
    return np.cumsum(np.random.default_rng(seed).standard_normal(n))


@pytest.mark.parametrize("seed", [0, 1, 2, 3, 4])
def test_best_hrs_partition_is_not_ho_alias_at_w700(seed):
    """config.BEST_HRS_PARTITION must exercise genuine partitioned pooling,
    not silently degenerate to compute_ho(), at the study's chosen window (W700)."""
    sig = _fbm(W700_N, seed)
    ho = compute_ho(sig, fs=cfg.FS)
    hrs = compute_hrs(sig, fs=cfg.FS, p=cfg.BEST_HRS_PARTITION)
    assert not np.isnan(hrs)
    assert hrs != ho, (
        f"compute_hrs(p={cfg.BEST_HRS_PARTITION}) matched compute_ho() exactly — "
        "this is the degenerate-fallback bug the Fase 2 fix addresses. If "
        "config.BEST_HRS_PARTITION changed, re-verify it against N=700 "
        "(see src/features/fractal.py compute_hrs docstring)."
    )


@pytest.mark.parametrize("p", [16, 32, 64])
def test_known_degenerate_hrs_partitions_still_equal_ho_at_w700(p):
    """Documents the (non-obvious) partition values that DO still degenerate
    to HO at N=700, so this doesn't get "rediscovered" as a surprise bug —
    see compute_hrs's docstring for why p=16 fails despite scale_max>scale_min."""
    sig = _fbm(W700_N, seed=7)
    ho = compute_ho(sig, fs=cfg.FS)
    hrs = compute_hrs(sig, fs=cfg.FS, p=p)
    assert hrs == ho


def test_precomputed_ho_matches_recomputed_ho():
    """The precomputed_ho fast path (Fase 1 perf fix) must return exactly
    what compute_hrs would have recomputed internally on fallback."""
    sig = _fbm(500, seed=3)  # N=500 -> p=64 always degenerates (subseries<10)
    ho = compute_ho(sig, fs=cfg.FS)
    hrs_no_cache = compute_hrs(sig, fs=cfg.FS, p=64)
    hrs_with_cache = compute_hrs(sig, fs=cfg.FS, p=64, precomputed_ho=ho)
    assert hrs_no_cache == hrs_with_cache == ho


# ---------------------------------------------------------------------------
# Golden-fixture regression (protects Fase 1 performance refactor)
# ---------------------------------------------------------------------------

def _regen_signal(name, n_samples, seed=42):
    """Recreate the exact same signals used by scripts/_gen_fractal_golden.py."""
    rng = np.random.default_rng(seed)
    signals = {}
    for n in (500, 700, 2000):
        signals[f"fbm_{n}"] = np.cumsum(rng.standard_normal((16, n)), axis=1)
    signals["white_700"] = rng.standard_normal((16, 700))
    t = np.arange(700)
    signals["trend_700"] = (np.tile(t * 0.01, (16, 1))
                             + rng.standard_normal((16, 700)) * 0.1)
    return signals[name]


@pytest.mark.skipif(not os.path.exists(os.path.join(FIXTURES_DIR, "fractal_golden.npz")),
                     reason="golden fixture not generated yet")
@pytest.mark.parametrize("name,n_samples", [
    ("fbm_500", 500), ("fbm_700", 700), ("fbm_2000", 2000),
    ("white_700", 700), ("trend_700", 700),
])
def test_compute_all_fractals_matches_golden(name, n_samples):
    golden = np.load(os.path.join(FIXTURES_DIR, "fractal_golden.npz"))
    sig = _regen_signal(name, n_samples)
    feats = compute_all_fractals(sig, fs=cfg.FS)
    np.testing.assert_allclose(feats, golden[name], rtol=1e-6, atol=1e-8,
                                err_msg=f"compute_all_fractals drifted for {name} "
                                        "vs tests/fixtures/fractal_golden.npz — if this "
                                        "is an intentional numeric change (e.g. the "
                                        "HRS_p64 fix), regenerate the fixture and "
                                        "document why.")
